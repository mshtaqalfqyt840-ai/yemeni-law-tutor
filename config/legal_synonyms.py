"""
قاموس المرادفات القانونية لتوسيع الاستعلامات (Query Expansion).
يساعد على دمج المصطلحات والمترادفات القانونية المتصلة لرفع دقة الاسترجاع الهجين.
"""

import re

LEGAL_SYNONYMS = {
    "كفالة": ["كفالة", "كفيل", "كافل", "مكفول", "ضمان", "ضامن", "مضمون", "الضمانة"],
    "ضمان": ["ضمان", "ضامن", "مضمون", "كفالة", "كفيل", "كافل", "مكفول"],
    "كفيل": ["كفيل", "كفالة", "كافل", "مكفول", "ضامن", "ضمان"],
    "ضامن": ["ضامن", "ضمان", "مضمون", "كفيل", "كفالة"],
    "رهن": ["رهن", "راهن", "مرتهن", "مرهون"],
    "بيع": ["بيع", "بائع", "مشتري", "مبيع", "ثمن", "شراء"],
    "إيجار": ["إيجار", "ايجار", "مؤجر", "مستأجر", "أجرة", "اجرة", "إجارة"],
    "وكالة": ["وكالة", "وكيل", "موكل"],
    "شركة": ["شركة", "شريك", "شركاء"],
    "شفعة": ["شفعة", "شفيع", "مشفوع"],
    "غصب": ["غصب", "غاصب", "مغصوب"],
    "عقد": ["عقد", "العقد", "متعاقدان", "تراضي", "أركان العقد"],
    "أركان": ["أركان", "اركان", "شروط", "تراضي"],
    "إرادة": ["إرادة", "ارادة", "تراضي", "رضا", "إكراه", "غلط", "تدليس", "غبن"],
    "عيوب": ["عيوب", "إكراه", "غلط", "تدليس", "غبن", "رضا", "تراضي"],
}


def expand_query_with_synonyms(query: str) -> str:
    """توسيع الاستعلام بإضافة الكلمات المرادفة الهامة لمنع الفقدان الكلمي."""
    if not query:
        return query
    
    words = query.strip().split()
    added_synonyms = set()

    for w in words:
        clean_w = re.sub(r"[^\w\s]", "", w).strip()
        # مطابقة الكلمة مع أو بدون ال التعريف
        raw_clean = clean_w[2:] if clean_w.startswith("ال") and len(clean_w) > 3 else clean_w

        for key, syns in LEGAL_SYNONYMS.items():
            if raw_clean == key or clean_w == key:
                for syn in syns:
                    if syn not in words and syn not in added_synonyms:
                        added_synonyms.add(syn)

    if added_synonyms:
        expanded = query + " " + " ".join(added_synonyms)
        return expanded

    return query
