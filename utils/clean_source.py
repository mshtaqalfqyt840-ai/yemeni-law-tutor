import os
import re


def clean_official_law_text(raw_text: str) -> str:
    """
    تنظيف وتوحيد شكلي مسبق للنص الرسمي للقانون المدني:
    1. توحيد الفواصل السطرية بين الأنظمة المخلتفة (\r\n -> \n).
    2. معالجة وتوحيد صياغة عناوين المواد لتستقر في بداية السطر دائمًا.
    3. تنظيف أي علامات أو رموز زائدة لتسهيل مهمة أداة التجزئة المقيدة بـ MULTILINE.
    """
    if not raw_text:
        return ""

    # 1. توحيد الفواصل السطرية
    text = raw_text.replace("\r\n", "\n").replace("\r", "\n")

    # 2. ضمان وجود سطر جديد قبل كل عنوان مادة رئيسي إذا لم يكن مسبوقاً بسطر جديد
    # لحماية رؤوس المواد وتأمين مطابقتها بمرساة بداية السطر ^
    text = re.sub(
        r"([^\n])\s*(الم[\u0640]*ادة|م[\u0640]*ادة)\s*\(?\s*([\d\u0660-\u0669]+)\s*\)?\s*:",
        r"\1\n\2(\3):",
        text,
    )

    return text
